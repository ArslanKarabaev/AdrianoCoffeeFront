// ── Текущий язык ──────────────────────────────
function getCurrentLang() {
    return localStorage.getItem('lang') || 'ru';
}

function setLang(lang) {
    localStorage.setItem('lang', lang);
    applyTranslations();
    // Перерисовываем меню если оно загружено
    if (typeof renderMenu === 'function' && typeof allMenuItems !== 'undefined') {
        renderMenu(allMenuItems);
    }
}

// ── Получить перевод ──────────────────────────
function t(key) {
    const lang = getCurrentLang();
    return translations[lang]?.[key] || translations['ru']?.[key] || key;
}

// ── Применить переводы к странице ─────────────
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = t(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = translated;
        } else {
            el.textContent = translated;
        }
    });

    // Обновляем переключатель языка
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === getCurrentLang());
    });
}

// ── Получить название блюда на нужном языке ───
function getDishName(item) {
    const lang = getCurrentLang();
    if (lang === 'en' && item.nameEn) return item.nameEn;
    if (lang === 'kg' && item.nameKg) return item.nameKg;
    return item.name;
}

function getDishDescription(item) {
    const lang = getCurrentLang();
    if (lang === 'en' && item.descriptionEn) return item.descriptionEn;
    if (lang === 'kg' && item.descriptionKg) return item.descriptionKg;
    return item.description;
}

// ── Инициализация ─────────────────────────────
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
});